"""Generate Kitchen Rat models.

Usage (Blender as a Python module, `pip install bpy`):
    python tools/blender/run.py            # everything
    python tools/blender/run.py props      # one group: props, characters, furniture, rooms
Or inside Blender: blender -b -P tools/blender/run.py -- props
Writes FBX files to art/<category>/ and a list to art/MODELS.md.
"""
import importlib
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib  # noqa: E402

args = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else sys.argv[1:]
groups = args or ['props', 'characters', 'furniture', 'rooms']
report = []
for g in groups:
    mod = importlib.import_module(g)
    for fn in mod.ALL:
        lib.reset()
        t = time.time()
        res = fn()
        if not isinstance(res, list):
            res = [res]
        for path, tris in res:
            rel = os.path.relpath(path, lib.ROOT)
            report.append((g, rel, tris))
            print('%-10s %-40s %6d tris  %.1fs' % (g, rel, tris, time.time() - t), flush=True)

if args == [] or len(groups) == 4:
    with open(os.path.join(lib.ROOT, 'MODELS.md'), 'w') as f:
        f.write('# Generated models\n\nAll models are generated by `tools/blender/run.py`. Units: metres, origin at the bottom centre, facing +Z in Unity.\n\n| Group | File | Triangles |\n|---|---|---|\n')
        for g, rel, tris in report:
            f.write('| %s | `%s` | %d |\n' % (g, rel, tris))
